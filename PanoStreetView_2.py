class NearestPointFinder:
    def add_index_to_shp(self, progress_bar):
        # Method to find the nearest point
        global point_layer, index, shapefile_path
        point_layer = QgsVectorLayer(shapefile_path, "points", "ogr")
        if not point_layer.isValid():
            raise ValueError("Invalid layer!")
        
        total_features = point_layer.featureCount()  # Total number of features in the point layer
        if total_features > 0:
            index = QgsSpatialIndex()
            completed = 0  # Initialize completed features counter
            progress_bar.setRange(0, total_features)  # Set the range of the progress bar
            for feature in point_layer.getFeatures():
                index.addFeature(feature)
                completed += 1
                progress_bar.setValue(completed)  # Update the progress bar
        else:
            print("No features found in the point layer.")
            QgsMessageLog.logMessage("No features found in the point layer.")
        print("Index added successfully.")
        QgsMessageLog.logMessage("Index added successfully.")

    def find_nearest_point_with_image(self, point_coordinate):
        if index is None:
            print("Spatial index is not initialized. Call add_index method first.")
            return None, None
        self.coords_str = point_coordinate.split('(')[1].split(')')[0]
        x, y = map(float, self.coords_str.split())
        point = QgsPointXY(x, y)

        nearest_ids = index.nearestNeighbor(point, 1)
        nearest_feature = point_layer.getFeature(nearest_ids[0])
        QgsMessageLog.logMessage("Found nearest image")
        azimuth_index = nearest_ids[0]
        point_name = nearest_feature["Name"]
        azimuth = nearest_feature["Azimuth"]
        print("Nearest image found.")

        return azimuth_index, point_name, azimuth
    
    def next_11_images(self, point_coordinate):
        if index is None:
            print("Spatial index is not initialized. Call add_index method first.")
            return None, None
        self.coords_str = point_coordinate.split('(')[1].split(')')[0]
        x, y = map(float, self.coords_str.split())
        point = QgsPointXY(x, y)

        all_index = []
        near_feature_all_dict = []

        near_id = index.nearestNeighbor(point, 1)[0]
        print(f"near_id-{near_id}")
        next_11_img_ids = index.nearestNeighbor(point, 3)
        next_11_img_ids.sort()


        QgsMessageLog.logMessage("Found near 11 points")
        # print(f"next_11_img_ids{next_11_img_ids}")

        l = 0
        for i in next_11_img_ids:
            all_index.append(i)
        print(f"sorted 11 index list-{all_index}")
        QgsMessageLog.logMessage("11 points sorted in ascending order")

        for i in all_index:
            near_feature = point_layer.getFeature(i)
            image_name = near_feature["Name"]
            azimuth = near_feature["Azimuth"]
            # Extract coordinates of the feature
            feature_geom = near_feature.geometry()
            feature_coords = feature_geom.asPoint()
            feature_x = feature_coords.x()
            feature_y = feature_coords.y()
            near_feature_dict = {"row": l, "index": i, "point_name": image_name, "azimuth": azimuth, "coordinates": str(feature_y) + ", " + str(feature_x)}
            near_feature_all_dict.append(near_feature_dict)
            l += 1
            json_file_path = os.path.join(base_folder, 'Image_to_copy.json')
            with open(json_file_path, 'w') as json_file:
                json.dump(near_feature_all_dict, json_file)
        QgsMessageLog.logMessage("Image_to_copy.json created")

