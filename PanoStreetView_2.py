class QuietHandler(SimpleHTTPRequestHandler):
    """Web server handler, which will not write any message
    in python console. As a result, no need to open python console
    in QGIS in order to make plugin work
    """

    def log_message(self, format, *args):
        pass

class HttpDaemon(QtCore.QThread):
    """Simple web server class
    """

    def __init__(self, parent, path):
        super(QThread, self).__init__()
        self.server_path = path
        self.server = None  # Initialize server attribute
        self.image_folder = image_folder  # Store the original image folder path

    def run(self):
        os.chdir(self.server_path)
        # Create a custom handler that can serve files from the image folder
        class CustomHandler(QuietHandler):
            def translate_path(self, path):
                # If the path starts with /images/, serve from the original image folder
                if path.startswith('/images/'):
                    image_name = path[8:]  # Remove '/images/' prefix
                    return os.path.join(self.server.image_folder, image_name)
                return super().translate_path(path)

        self.server = HTTPServer((HOST, PORT), CustomHandler)
        self.server.image_folder = self.image_folder  # Pass image folder to handler
        self.server.serve_forever()
        QgsMessageLog.logMessage("Serving server")

    def stop(self):
        if self.server:
            self.server.shutdown()
            self.server.socket.close()
            QgsMessageLog.logMessage("Closing socket")

    def __del__(self):
        self.stop()  # Ensure server is stopped and socket is closed when instance is deleted
        QgsMessageLog.logMessage("Server stopped")
